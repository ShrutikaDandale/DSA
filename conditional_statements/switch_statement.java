package conditional_statements;

public class switch_statement {
    public static void main(String[] args) {
        int num = 2;
        switch(num){
            case 1 : System.out.println("samosa");
            break;

            case 2 : System.out.println("mango shake");
            break;

            default : System.out.println("none");
        }
    }
}
